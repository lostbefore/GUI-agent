            "- Action error rate: failed action attempts divided by all action attempts.",
            "- Average retries: arithmetic mean automatic retry count per task.",
            "- Analysis dimensions: application, difficulty, and screen resolution.",
            "",
            "## 3. 20 \u9879\u57fa\u51c6\u4efb\u52a1\u96c6",
            "",
            "| ID | Task | Application | Category | Difficulty | Resolution | Expected actions |",
            "|---|---|---|---|---|---|---:|",
