            "",
            "All records in this report use the `controlled` mode. Deterministic substitutes exercise task orchestration, retry, logging, and aggregation without operating a real desktop. These measurements are a reproducible runtime baseline and are not presented as external-application or model-generalization results.",
            "",
            "## 2. \u8bc4\u4f30\u8303\u56f4\u4e0e\u6307\u6807",
            "",
            "- Task success rate: successful tasks divided by all tasks.",
