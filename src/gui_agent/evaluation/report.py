            "",
            "The task set covers Browser, File Explorer, Notepad, Calculator, and Windows Settings; it includes basic, intermediate, and advanced workflows at 1366x768, 1920x1080, and 2560x1440.",
            "",
            "## 4. \u6574\u4f53\u7ed3\u679c",
            "",
            *_table([overall]),
            "",
            "## 5. \u5206\u7ec4\u6027\u80fd\u5206\u6790",
            "",
            "### 5.1 \u6309\u96be\u5ea6",
