            "",
            "Ui-TARS describes a native GUI agent that uses screenshots as its perception input and emphasizes unified action modeling, systematic reasoning, and reflective trace training. Claude Computer Use documents a loop where the model selects a computer tool, the client executes it, and the result is returned for the next turn. This is a technical-route comparison; public scores from different environments are not directly compared with this controlled benchmark.",
